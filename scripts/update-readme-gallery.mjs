#!/usr/bin/env node
/**
 * Reads docs/screenshots/manifest.json and rewrites everything between the
 * SCREENSHOTS:START / SCREENSHOTS:END markers in README.md and README.tr.md.
 * The manifest is produced by `npm run screenshots`.
 */
import { existsSync } from "node:fs";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const ROOT = process.cwd();
const SHOT_DIR = path.join(ROOT, "docs", "screenshots");
const MANIFEST = path.join(SHOT_DIR, "manifest.json");
const START = "<!-- SCREENSHOTS:START -->";
const END = "<!-- SCREENSHOTS:END -->";

const TARGETS = [
  {
    file: "README.md",
    locale: "en",
    title: (shot) => shot.title,
    caption: (shot) => shot.caption,
    darkSummary: "Dark mode",
    note: (manifest) =>
      `<!-- Generated by \`npm run screenshots\` · ${manifest.generatedAt} · ${manifest.viewport.width}x${manifest.viewport.height}@${manifest.deviceScaleFactor ?? 1}x · do not edit by hand -->`,
  },
  {
    file: "README.tr.md",
    locale: "tr",
    title: (shot) => shot.titleTr ?? shot.title,
    caption: (shot) => shot.captionTr ?? shot.caption,
    darkSummary: "Koyu tema",
    note: (manifest) =>
      `<!-- \`npm run screenshots\` tarafından üretildi · ${manifest.generatedAt} · ${manifest.viewport.width}x${manifest.viewport.height}@${manifest.deviceScaleFactor ?? 1}x · elle düzenlemeyin -->`,
  },
];

const fail = (message) => {
  console.error(`x ${message}`);
  process.exit(1);
};

if (!existsSync(MANIFEST)) {
  fail(
    `${path.relative(ROOT, MANIFEST)} is missing — run \`npm run screenshots\` first.`,
  );
}

const manifest = JSON.parse(await readFile(MANIFEST, "utf8"));

// Only shots that actually exist on disk — a skipped shot keeps its old PNG
// and therefore stays in the gallery.
const available = manifest.shots.filter((shot) =>
  existsSync(path.join(SHOT_DIR, `${shot.file}.webp`)),
);

if (available.length === 0) {
  fail("No screenshots found — the gallery was left untouched.");
}

// A README shows its own language's shots plus the language-neutral ones.
const groupsFor = (locale) => {
  const groups = new Map();
  for (const shot of available) {
    if (shot.locale !== locale && shot.locale !== "shared") continue;
    if (!groups.has(shot.group)) groups.set(shot.group, { shot, byTheme: {} });
    groups.get(shot.group).byTheme[shot.theme] = shot.file;
  }
  return groups;
};

// One full-width image per view: at 1920x1080 a side-by-side pair would shrink
// the UI past the point of being readable. The dark variant sits in a
// collapsed <details> so the page stays short.
const renderBlock = (target, groups) => {
  const img = (file, alt) =>
    `<img src="docs/screenshots/${file}.webp" alt="${alt}" width="100%">`;

  const body = [...groups.values()]
    .map(({ shot, byTheme }) => {
      const title = target.title(shot);
      const section = [`#### ${title}`, "", target.caption(shot), ""];
      if (byTheme.light) section.push(img(byTheme.light, title), "");
      if (byTheme.dark) {
        section.push(
          "<details>",
          `<summary>${target.darkSummary}</summary>`,
          "",
          img(byTheme.dark, `${title} — dark`),
          "",
          "</details>",
        );
      }
      return section.join("\n").trimEnd();
    })
    .join("\n\n");

  return [START, "", target.note(manifest), "", body, "", END].join("\n");
};

let changed = 0;
for (const target of TARGETS) {
  const file = path.join(ROOT, target.file);
  if (!existsSync(file)) {
    fail(`${target.file} is missing — the gallery has nowhere to go.`);
  }

  const groups = groupsFor(target.locale);
  if (groups.size === 0) {
    fail(`No ${target.locale} screenshots found — ${target.file} left untouched.`);
  }

  const source = await readFile(file, "utf8");
  const start = source.indexOf(START);
  const end = source.indexOf(END);
  if (start === -1 || end === -1 || end < start) {
    fail(`${target.file} is missing the ${START} / ${END} markers.`);
  }

  const next =
    source.slice(0, start) + renderBlock(target, groups) + source.slice(end + END.length);
  if (next === source) continue;

  await writeFile(file, next);
  changed += 1;
  console.log(`✓ ${target.file} gallery updated (${groups.size} sections).`);
}

if (changed === 0) console.log("- Galleries already up to date.");
