export type LucidePropertyIconId =
  (typeof LUCIDE_PROPERTY_ICONS)[number]["id"];
export type NotionPropertyIconId = `notion:${string}`;
export type PropertyIconId = LucidePropertyIconId | NotionPropertyIconId;

export interface NotionPropertyIconDefinition {
  id: NotionPropertyIconId;
  label: string;
  keywords: string;
  paths: string[];
}

export const NOTION_PROPERTY_ICONS =
  notionPropertyIcons as NotionPropertyIconDefinition[];
export const PROPERTY_ICONS = [
  ...NOTION_PROPERTY_ICONS,
  ...LUCIDE_PROPERTY_ICONS,
] as const;

const PROPERTY_ICON_ID_SET = new Set<string>(
  PROPERTY_ICONS.map((icon) => icon.id),
);
const LUCIDE_PROPERTY_ICON_ID_SET = new Set<string>(
  LUCIDE_PROPERTY_ICONS.map((icon) => icon.id),
);
const NOTION_PROPERTY_ICON_BY_ID = new Map(
  NOTION_PROPERTY_ICONS.map((icon) => [icon.id, icon]),
);

export function isPropertyIconId(value: string): value is PropertyIconId {
  return PROPERTY_ICON_ID_SET.has(value);
}

export function isLucidePropertyIconId(
  value: string,
): value is LucidePropertyIconId {
  return LUCIDE_PROPERTY_ICON_ID_SET.has(value);
}

export function getNotionPropertyIcon(value: string) {
  return NOTION_PROPERTY_ICON_BY_ID.get(value as NotionPropertyIconId);
}
